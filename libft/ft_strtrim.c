#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char const	*start;
	char const	*end;

	if (!s1 || !set)
		return (NULL);
	start = s1;
	while (*start && ft_strchr(set, *start))
		start++;
	end = s1;
	while (*end)
		end++;
	while (end > start && ft_strchr(set, *(end - 1)))
		end--;
	return (ft_substr(s1, start - s1, end - start));
}
